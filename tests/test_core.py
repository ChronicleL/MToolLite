class TestTextGuard(unittest.TestCase):
    def test_protect_and_restore(self) -> None:
        src = r"\C[1]勇者\N[1]\C[0]は%1に\V[10]のダメージ！\n<br/>\{やった！\}"
        protected, tokens = protect_text(src)
        self.assertNotIn(r"\C[1]", protected)
        self.assertNotIn("%1", protected)
        self.assertNotIn("\n", protected)
        # Simulate translation keeping placeholders intact
        fake_tr = protected.replace("勇者", "Hero").replace("のダメージ！", " damage!").replace("やった！", "Yay!")
        restored = restore_text(fake_tr, tokens)
        self.assertEqual(
            restored,
            r"\C[1]Hero\N[1]\C[0]は%1に\V[10] damage!\n<br/>\{Yay!\}",
        )


class TestDetectorAndMvMzPipeline(unittest.TestCase):
    def test_detect_various_engines(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)

            # MZ
            mz = root / "mz_game"
            (mz / "js").mkdir(parents=True)
            (mz / "data").mkdir(parents=True)
            (mz / "js" / "rmmz_core.js").write_text("", encoding="utf-8")
            (mz / "data" / "System.json").write_text("{}", encoding="utf-8")
            self.assertEqual(detect_engine(mz).engine, "RPG Maker MZ")

            # MV (www layout)
            mv = root / "mv_game"
            (mv / "www" / "js").mkdir(parents=True)
            (mv / "www" / "data").mkdir(parents=True)
            (mv / "www" / "data" / "System.json").write_text("{}", encoding="utf-8")
            (mv / "Game.exe").write_text("", encoding="utf-8")
            info_mv = detect_engine(mv / "Game.exe")
            self.assertEqual(info_mv.engine, "RPG Maker MV")
            self.assertEqual(info_mv.data_dir, mv / "www" / "data")

            # VX Ace
            vxa = root / "vxa_game"
            vxa.mkdir()
            (vxa / "Game.ini").write_text("[Game]\nLibrary=System\\RGSS301.dll\n", encoding="utf-8")
            self.assertEqual(detect_engine(vxa).engine, "RPG Maker VX Ace")

            # Wolf RPG
            wolf = root / "wolf_game"
            wolf.mkdir()
            (wolf / "Data.wolf").write_text("", encoding="utf-8")
            self.assertEqual(detect_engine(wolf).engine, "Wolf RPG")

    def test_extract_translate_mount_unmount(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            game = Path(tmp) / "sample_mz"
            data_dir = game / "data"
            js_dir = game / "js"
            data_dir.mkdir(parents=True)
            js_dir.mkdir(parents=True)
            (js_dir / "rmmz_core.js").write_text("", encoding="utf-8")

            # plugins.js
            plugins_js = js_dir / "plugins.js"
            original_plugins_content = (
                "// Generated by RPG Maker.\n"
                "var $plugins =\n"
                '[{"name":"ExistingPlugin","status":true,"description":"","parameters":{}}];\n'
            )
            plugins_js.write_text(original_plugins_content, encoding="utf-8")

            # System.json & Actors.json & Map001.json
            (data_dir / "System.json").write_text(
                json.dumps(
                    {
                        "gameTitle": "冒険の書",
                        "currencyUnit": "G",
                        "elements": ["", "物理", "炎"],
                        "terms": {"basic": ["レベル"], "commands": ["戦う"], "params": ["最大HP"], "messages": {"actionFailure": "%1には効かなかった！"}},
                    },
                    ensure_ascii=False,
                ),
                encoding="utf-8",
            )
            (data_dir / "Actors.json").write_text(
                json.dumps([None, {"id": 1, "name": "リード", "nickname": "勇者", "profile": "旅に出た少年"}], ensure_ascii=False),
                encoding="utf-8",
            )
            (data_dir / "Map001.json").write_text(
                json.dumps(
                    {
                        "displayName": "始まりの村",
                        "events": [
                            None,
                            {
                                "id": 1,
                                "pages": [
                                    {
                                        "list": [
                                            {"code": 101, "parameters": ["", 0, 0, 2, "村人"]},
                                            {"code": 401, "parameters": [r"\C[1]こんにちは！\C[0]"]},
                                            {"code": 102, "parameters": [["はい", "いいえ"], 1, 0, 2, 0]},
                                        ]
                                    }
                                ],
                            },
                        ],
                    },
                    ensure_ascii=False,
                ),
                encoding="utf-8",
            )

            # 1. Extract
            texts = extract_mvmz_texts(game)
            self.assertIn("冒険の書", texts)
            self.assertIn("リード", texts)
            self.assertIn("村人", texts)
            self.assertIn(r"\C[1]こんにちは！\C[0]", texts)
            self.assertIn("はい", texts)
            self.assertNotIn("G", [])  # sanity

            dict_path = game / "ManualTransFile.json"
            merged, added = merge_extracted({}, texts)
            self.assertEqual(added, len(texts))
            save_json_dict(dict_path, merged)

            # 2. Translate (mock LLM)
            def mock_llm(_cfg: TranslatorConfig, _sys: str, usr: str) -> str:
                payload = json.loads(usr)
                out_items = [
                    {"id": it["id"], "text": f"[ZH]{it['text']}"}
                    for it in payload["items"]
                ]
                return json.dumps({"items": out_items}, ensure_ascii=False)

            cfg = TranslatorConfig(api_key="test-key", batch_size=5, max_workers=2)
            done, total = translate_dictionary_file(dict_path, cfg, llm_caller=mock_llm)
            self.assertEqual(done, total)
            loaded = load_json_dict(dict_path)
            self.assertEqual(get_untranslated(loaded), [])
            self.assertEqual(loaded[r"\C[1]こんにちは！\C[0]"], r"[ZH]\C[1]こんにちは！\C[0]")

            # 3. Mount
            mounted = mount_mvmz(game, dict_path=dict_path, capture_untranslated=True)
            self.assertTrue(mounted["plugin"].is_file())
            self.assertTrue(mounted["dictionary"].is_file())
            self.assertIn(PLUGIN_NAME, plugins_js.read_text(encoding="utf-8"))

            # 4. Unmount
            self.assertTrue(unmount_mvmz(game))
            self.assertFalse(mounted["plugin"].is_file())
            self.assertEqual(plugins_js.read_text(encoding="utf-8"), original_plugins_content)


if __name__ == "__main__":
    unittest.main()
